// Writes integration_test/support/crate_vectors.g.dart: the shared crate's test vectors as a Dart string, so the test that
// runs in the app on a simulator has them without the file being an asset of every build (it would ship in Release).
// `node mobile/tool/crate-vectors.mjs` rewrites it; `--check` exits 1 when it is stale (CI runs it, and so does
// test/core_vectors_test.dart).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const SOURCE = here('../../crates/bobix-link/tests/vectors.json');
const OUT = here('../integration_test/support/crate_vectors.g.dart');

export function render(json) {
  if (json.includes("'''")) throw new Error("vectors.json holds ''' and cannot go in a raw Dart string");
  return `// GENERATED by mobile/tool/crate-vectors.mjs from crates/bobix-link/tests/vectors.json. Do not edit.\n// dart format off\n\nconst crateVectorsJson = r'''${json}''';\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(readFileSync(SOURCE, 'utf8'));
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (have !== text) { console.error('integration_test/support/crate_vectors.g.dart is out of date: run `node mobile/tool/crate-vectors.mjs`'); process.exit(1); }
  } else writeFileSync(OUT, text);
}
