// Writes the phone's Dart string table from the `phone.*` keys of src/ui/i18n.js (the single source of every string).
// `node mobile/tool/strings.mjs` regenerates; `--check` exits 1 when the committed file is stale. A key that lacks a
// language, or whose {placeholders} differ between languages, is an error.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const OUT = here('../lib/l10n/strings.g.dart');
const LANGS = ['en', 'vi'];

const vars = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');
// Dart single-quoted literal: `$` and `\` would otherwise be read by Dart.
const lit = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

export function render(STR) {
  const keys = new Set(LANGS.flatMap((l) => Object.keys(STR[l]).filter((k) => k.startsWith('phone.'))));
  const problems = [];
  for (const k of keys) {
    for (const l of LANGS) if (!STR[l][k]) problems.push(`${k} has no ${l} text`);
    if (LANGS.every((l) => STR[l][k]) && vars(STR.en[k]) !== vars(STR.vi[k])) problems.push(`${k} has different {placeholders} in en and vi`);
  }
  if (problems.length) throw new Error(problems.join('\n'));
  const sorted = [...keys].sort();
  const table = LANGS.map((l) => `  '${l}': {\n${sorted.map((k) => `    ${lit(k)}: ${lit(STR[l][k])},`).join('\n')}\n  },`).join('\n');
  return `// GENERATED by mobile/tool/strings.mjs from the phone.* keys of src/ui/i18n.js. Do not edit.\n\nconst Map<String, Map<String, String>> phoneStrings = {\n${table}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { STR } = createRequire(import.meta.url)('../../src/ui/i18n.js');
  const text = render(STR);
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
    if (have !== text) { console.error('mobile/lib/l10n/strings.g.dart is out of date: run `node mobile/tool/strings.mjs`'); process.exit(1); }
  } else writeFileSync(OUT, text);
}
