// Writes the phone's string tables (the Dart table, the iOS InfoPlist.strings) from the `phone.*` keys of src/ui/i18n.js
// (the single source of every string). `node mobile/tool/strings.mjs` regenerates; `--check` exits 1 when a committed file is stale. A key that lacks a
// language, or whose {placeholders} differ between languages, is an error.
import { createRequire } from 'node:module';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const LANGS = ['en', 'vi'];

const vars = (s) => [...s.matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(',');
// Dart single-quoted literal: `$` and `\` would otherwise be read by Dart.
const lit = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

export function render(STR) {
  const keys = new Set(LANGS.flatMap((l) => Object.keys(STR[l]).filter((k) => k.startsWith('phone.'))));
  const problems = [];
  for (const k of keys) {
    for (const l of LANGS) if (!STR[l][k]) problems.push(`${k} has no ${l} text`);
    if (LANGS.every((l) => STR[l][k]) && vars(STR.en[k]) !== vars(STR.vi[k])) problems.push(`${k} has different {placeholders} in en and vi`);
  }
  if (problems.length) throw new Error(problems.join('\n'));
  const sorted = [...keys].sort();
  const table = LANGS.map((l) => `  '${l}': {\n${sorted.map((k) => `    ${lit(k)}: ${lit(STR[l][k])},`).join('\n')}\n  },`).join('\n');
  return `// GENERATED by mobile/tool/strings.mjs from the phone.* keys of src/ui/i18n.js. Do not edit.\n// dart format off\n\nconst Map<String, Map<String, String>> phoneStrings = {\n${table}\n};\n`;
}

// The iOS permission texts the system shows (Info.plist keys) in each language: en.lproj / vi.lproj InfoPlist.strings.
const plistLit = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
export function renderInfoPlist(STR, lang) {
  const text = STR[lang]['phone.faceid.usage'];
  if (!text) throw new Error(`phone.faceid.usage has no ${lang} text`);
  return `/* GENERATED by mobile/tool/strings.mjs from src/ui/i18n.js. Do not edit. */\n"NSFaceIDUsageDescription" = ${plistLit(text)};\n`;
}

// The texts of a push that iOS or the notification service extension shows without Dart: the relay names the first two
// by key (`title-loc-key`, `loc-key`) and the system resolves them from the app's Localizable.strings; the extension
// has its own table for the texts it writes when it opens a notice.
export const PUSH_NATIVE = {
  'bobix.push.title': 'phone.push.generic.title',
  'bobix.push.body': 'phone.push.generic.body',
  'bobix.push.closed': 'phone.push.closed',
  'bobix.push.done.title': 'phone.push.done.generic.title',
  'bobix.push.done.body': 'phone.push.done.generic.body',
};
export function renderLocalizable(STR, lang) {
  const lines = Object.entries(PUSH_NATIVE).map(([native, key]) => {
    const text = STR[lang][key];
    if (!text) throw new Error(`${key} has no ${lang} text`);
    return `${plistLit(native)} = ${plistLit(text)};`;
  });
  return `/* GENERATED by mobile/tool/strings.mjs from src/ui/i18n.js. Do not edit. */\n${lines.join('\n')}\n`;
}

/** Every generated file: path (from the repository root) to its text. */
export function outputs(STR) {
  const out = { 'mobile/lib/l10n/strings.g.dart': render(STR) };
  for (const lang of LANGS) {
    out[`mobile/ios/Runner/${lang}.lproj/InfoPlist.strings`] = renderInfoPlist(STR, lang);
    for (const dir of ['Runner', 'NotificationService']) out[`mobile/ios/${dir}/${lang}.lproj/Localizable.strings`] = renderLocalizable(STR, lang);
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { STR } = createRequire(import.meta.url)('../../src/ui/i18n.js');
  const root = here('../../');
  const stale = [];
  for (const [path, text] of Object.entries(outputs(STR))) {
    const file = root + path;
    if (process.argv.includes('--check')) {
      let have = '';
      try { have = readFileSync(file, 'utf8'); } catch { /* missing counts as stale */ }
      if (have !== text) stale.push(path);
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
    }
  }
  if (stale.length) { console.error(`${stale.join(', ')} out of date: run \`node mobile/tool/strings.mjs\``); process.exit(1); }
}
